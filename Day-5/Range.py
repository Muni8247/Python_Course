#Range(Start, Stop, Step_Size)
a=range(10)
for i in a:
    print(i)


print("**************************************")



b=range(2,10)
for j in b:
    print(j)


print("**************************************")
c=range(2,15,2)
for x in c:
    print(x)


print("**************************************")



d=range(2,20,-3)
for z in d:
    print(z)

print("**************************************")

e=range(10,0,-1)
for y in e:
    print(y)